import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { loadGuideData, validateGuideData } from './validate.mjs';

const root = process.cwd();
const guide = validateGuideData(await loadGuideData(root));

const ACCESS_LABEL = {
  'free-tier': 'Free tier',
  free: 'Free',
  'open-source': 'Open source',
  'self-hosted': 'Self-hosted',
};

function humanDate(isoDate) {
  return new Intl.DateTimeFormat('en-US', {
    month: 'long',
    day: 'numeric',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(new Date(`${isoDate}T00:00:00Z`));
}

function mdCell(value) {
  return String(value).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

function buildPayload(guideData) {
  return {
    meta: {
      ...guideData.meta,
      tool_count: guideData.tools.length,
      category_count: guideData.categories.length,
    },
    categories: guideData.categories.map(({ tools, ...category }) => ({
      ...category,
      count: tools.length,
    })),
    tools: guideData.tools,
  };
}

function buildToolsIndex(guideData) {
  const { meta, categories } = guideData;
  const date = humanDate(meta.last_verified);
  const rows = categories.map((category) => {
    const starts = category.start_here
      .map((id) => {
        const tool = category.tools.find((candidate) => candidate.id === id);
        return `[${mdCell(tool.name)}](${category.id}.md#tool-${tool.id})`;
      })
      .join(', ');
    return `| [${mdCell(category.name)}](${category.id}.md) | ${mdCell(category.short)} | ${category.tools.length} | ${starts} |`;
  });

  return `<!-- Generated by scripts/build.mjs. Do not edit by hand. -->
# The tool directory

All **${guideData.tools.length} tools** in one place, organized into **${categories.length} categories**. Use the category pages when you want context, limits, and links together.

**Last verified:** ${date}  
**Guide edition:** ${meta.edition}

> ${meta.disclaimer}

| Category | Focus | Tools | Start here |
| --- | --- | ---: | --- |
${rows.join('\n')}

## A five-minute way to use this directory

1. Pick the category that matches the job, not the flashiest tool name.
2. Read **What is free** and **Limits** before creating an account.
3. Follow the official link and confirm the current allowance.
4. Try one small, non-sensitive task.
5. Decide only after the tool has earned a place in your routine.

## Keep going

- [Free AI Tools Mega Guide](../README.md)
- [Start here: paths by situation](../start-here.md)
- [Free-tier safety checklist](../free-tier-safety.md)
- [Local-first AI](../local-ai.md)
- [Agents and MCP, carefully](../agents-and-mcp.md)
- [Free AI coding and GitHub](../free-ai-coding.md)
- [AI for healthcare learners](../healthcare-learners.md)
- [Plain-English glossary](../glossary.md)

**Reality check:** free tiers are moving targets. A plan can change the day after this guide is verified. The provider's current terms always win.

---

Part of the **Free AI Tools Mega Guide** from **ASDALE DYNAMICS, LLC**. Copyright (c) 2026 Asdale Dynamics, LLC.
`;
}

function buildCategoryDoc(category, meta, allCategories) {
  const date = humanDate(meta.last_verified);
  const startNames = category.start_here
    .map((id) => {
      const tool = category.tools.find((candidate) => candidate.id === id);
      return `[${tool.name}](#tool-${tool.id})`;
    })
    .join(' · ');

  const tools = category.tools
    .map((tool) => {
      return `<a id="tool-${tool.id}"></a>

### ${tool.name}

\`${ACCESS_LABEL[tool.access]}\` · Last verified: ${tool.last_verified}

- **What is free:** ${tool.free}
- **Sign-up notes:** ${tool.signup}
- **Limits:** ${tool.limits}
- **Best for:** ${tool.best_for}
- **Official link:** <${tool.url}>
- **Tags:** ${tool.tags.map((tag) => `\`${tag}\``).join(' ')}
`;
    })
    .join('\n---\n\n');

  const index = allCategories.findIndex((item) => item.id === category.id);
  const previous = allCategories[index - 1];
  const next = allCategories[index + 1];
  const navigation = [
    previous ? `← [${previous.name}](${previous.id}.md)` : '← [All categories](README.md)',
    next ? `[${next.name}](${next.id}.md) →` : '[All categories](README.md) →',
  ].join(' · ');

  return `<!-- Generated by scripts/build.mjs from data/categories/${category.id}.json. Do not edit by hand. -->
# ${category.name}

${category.description}

**Last verified:** ${date} · **${category.tools.length} tools**

[Back to the guide](../README.md) · [All categories](README.md) · [Safety checklist](../free-tier-safety.md)

> **Category tip:** ${category.tip}

**Start here:** ${startNames}

## All ${category.tools.length} tools

${tools}
---

${navigation}

Free tiers change. Always confirm current terms on the official site. This page is educational information, not an endorsement or a guarantee.
`;
}

await mkdir(path.join(root, 'site/data'), { recursive: true });
await mkdir(path.join(root, 'docs/tools'), { recursive: true });

const payload = buildPayload(guide);
await writeFile(path.join(root, 'site/data/tools.json'), `${JSON.stringify(payload, null, 2)}\n`);

await writeFile(path.join(root, 'docs/tools/README.md'), buildToolsIndex(guide));

for (const category of guide.categories) {
  const markdown = buildCategoryDoc(category, guide.meta, guide.categories);
  await writeFile(path.join(root, 'docs/tools', `${category.id}.md`), markdown);
}

console.log(`Built ${guide.tools.length} tools across ${guide.categories.length} categories.`);
console.log('Wrote site/data/tools.json and docs/tools/*.md.');
