test('site HTML uses only local assets and safe external links', async () => {
  for (const page of ['index.html', 'about.html']) {
    const html = await read(path.join(SITE, page));
    const external = htmlLinks(html).filter((link) => /^[a-z]+:/i.test(link) || link.startsWith('//'));
    for (const link of external) {
      assert.match(link, /^https:\/\//, `${page} has a non-HTTPS external link: ${link}`);
    }

    assert.ok(html.includes("default-src 'self'"), `${page} is missing a restrictive CSP`);
    assert.ok(!/unsafe-inline|unsafe-eval/.test(html), `${page} CSP allows unsafe inline code`);
    assert.ok(!/<script(?![^>]*\bsrc=)[^>]*>/i.test(html), `${page} has an inline script`);
    assert.ok(!/\sstyle="/i.test(html), `${page} contains an inline style blocked by its CSP`);
    assert.ok(!/\son[a-z]+\s*=/i.test(html), `${page} contains an inline event handler`);
    assert.ok(!/javascript:/i.test(html), `${page} contains a javascript: URL`);

    for (const link of htmlLinks(html)) {
      if (link.startsWith('#')) {
        assert.ok(htmlHasId(html, link.slice(1)), `${page} links to a missing anchor ${link}`);
        continue;
      }
      if (/^(https?:|\/\/|mailto:|tel:)/i.test(link)) continue;
      const [rawPath, fragment] = link.split('#');
      const target = path.join(SITE, rawPath || page);
      const targetContent = await read(target);
      assert.ok(targetContent.length > 0, `${page} links to a missing file ${link}`);
      if (fragment) {
        if (target.endsWith('.html')) {
          assert.ok(htmlHasId(targetContent, fragment), `${page} links to missing ${link}`);
        }
      }
    }

    for (const tag of html.matchAll(/<a\b[^>]*target="_blank"[^>]*>/gi)) {
      assert.match(tag[0], /rel="noopener noreferrer"/, `${page} has an unsafe new-tab link`);
    }
  }

  const css = await read(path.join(SITE, 'assets/styles.css'));
  assert.ok(!/@import\s+url\(\s*['"]?https?:/i.test(css), 'CSS imports a remote stylesheet');
  assert.ok(!/url\(\s*['"]?https?:/i.test(css), 'CSS loads a remote resource');
  assert.ok(!/fonts\.google|use\.typekit|cdn\./i.test(css));

  const app = await read(path.join(SITE, 'assets/app.js'));
  assert.ok(!/\.innerHTML\s*=|\.outerHTML\s*=/.test(app), 'app.js assigns raw HTML');
  assert.ok(!/fetch\(\s*['"]https?:/.test(app), 'app.js fetches a remote URL');
  assert.ok(app.includes("fetch('data/tools.json'"));
  assert.ok(app.includes("target = '_blank'") && app.includes("link.rel = 'noopener noreferrer'"));
});

test('all local Markdown links and anchors resolve', async () => {
  const markdownFiles = [path.join(ROOT, 'README.md'), ...await walk(DOCS, '.md')];
  const anchorCache = new Map();

  async function anchorsFor(file) {
    if (!anchorCache.has(file)) anchorCache.set(file, markdownHeadings(await read(file)));
    return anchorCache.get(file);
  }

  for (const file of markdownFiles) {
    const content = await read(file);
    for (const target of markdownLinks(content)) {
      if (/^(https?:|mailto:|tel:|\/\/)/i.test(target)) continue;
      const [rawPath, rawFragment] = target.split('#');
      const targetFile = rawPath
        ? path.resolve(path.dirname(file), decodeURIComponent(rawPath))
        : file;
      let targetContent;
      try {
        targetContent = await read(targetFile);
      } catch {
        assert.fail(`${path.relative(ROOT, file)} links to missing file: ${target}`);
      }
      if (rawFragment) {
        const fragment = decodeURIComponent(rawFragment);
        if (targetFile.endsWith('.md')) {
          const anchors = await anchorsFor(targetFile);
          assert.ok(anchors.has(fragment), `${path.relative(ROOT, file)} links to missing anchor: ${target}`);
        } else if (targetFile.endsWith('.html')) {
          assert.ok(htmlHasId(targetContent, fragment), `${path.relative(ROOT, file)} links to missing anchor: ${target}`);
        }
      }
    }
  }

  const handBooks = [
    'README.md',
    'docs/README.md',
    'docs/start-here.md',
    'docs/free-tier-safety.md',
    'docs/local-ai.md',
    'docs/glossary.md',
    'docs/tools/README.md',
  ];
  for (const relative of handBooks) {
    const content = await read(path.join(ROOT, relative));
    assert.ok(content.startsWith('# ') || content.startsWith('<!--'), `${relative} should start with a title or generator note`);
    assert.ok(content.length > 1000, `${relative} looks too thin`);
  }
});
